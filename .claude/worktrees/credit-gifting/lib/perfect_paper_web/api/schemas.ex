defmodule PerfectPaperWeb.Api.Schemas do
  @moduledoc """
  OpenAPI schema modules for the PerfectPaper REST API.

  Each inner module uses the `OpenApiSpex.schema/1` macro and mirrors the exact
  field names and types returned by the JSON views (`history_json.ex`,
  `credit_json.ex`) and the error envelope in `fallback_controller.ex`.
  """

  alias OpenApiSpex.Schema

  defmodule Comment do
    @moduledoc "A single piece of referee-grade feedback on a manuscript passage."

    require OpenApiSpex

    OpenApiSpex.schema(%{
      title: "Comment",
      type: :object,
      description:
        "One comment generated by a PerfectPaper review: the quoted passage, " <>
          "a suggested rewrite, an explanation, a category tag, the writer's " <>
          "action status, and an ordinal position in the document. Human comments " <>
          "also carry author_type, author_id, body, and parent_id.",
      properties: %{
        id: %Schema{
          type: :string,
          format: :uuid,
          description: "UUID of the comment."
        },
        original_text: %Schema{
          type: :string,
          nullable: true,
          description: "The verbatim passage from the manuscript that this comment addresses."
        },
        suggestion: %Schema{
          type: :string,
          nullable: true,
          description: "The suggested replacement or improvement."
        },
        explanation: %Schema{
          type: :string,
          nullable: true,
          description: "Referee-grade rationale for the suggestion."
        },
        category: %Schema{
          type: :string,
          nullable: true,
          description: "Feedback category tag (e.g. \"clarity\", \"grammar\", \"structure\")."
        },
        status: %Schema{
          type: :string,
          enum: ["open", "dismissed", "addressed"],
          description:
            "The writer's current action on this comment. " <>
              "`open` — not yet acted on; " <>
              "`dismissed` — writer chose to ignore; " <>
              "`addressed` — writer has resolved the issue."
        },
        position: %Schema{
          type: :integer,
          nullable: true,
          description: "Ordinal position of the comment within the document (1-based)."
        },
        author_type: %Schema{
          type: :string,
          enum: ["ai", "user"],
          nullable: true,
          description: "`ai` for AI-generated feedback; `user` for human collaborator comments."
        },
        author_id: %Schema{
          type: :string,
          format: :uuid,
          nullable: true,
          description:
            "UUID of the user who wrote this comment. Present only when author_type is `user`."
        },
        body: %Schema{
          type: :string,
          nullable: true,
          description: "Free-text body of a human comment. Null for AI-generated comments."
        },
        parent_id: %Schema{
          type: :string,
          format: :uuid,
          nullable: true,
          description:
            "UUID of the parent comment when this is a threaded reply. Null for top-level comments."
        }
      },
      required: [:id, :status],
      example: %{
        id: "3fa85f64-5717-4562-b3fc-2c963f66afa6",
        original_text: "The results shows a significant improvement.",
        suggestion: "The results show a significant improvement.",
        explanation:
          "Subject–verb agreement: \"results\" is plural and requires \"show\", not \"shows\".",
        category: "grammar",
        status: "open",
        position: 12,
        author_type: "ai",
        author_id: nil,
        body: nil,
        parent_id: nil
      }
    })
  end

