  defmodule Error do
    @moduledoc """
    The FastAPI-style error envelope used by FallbackController.

    `detail` is either a plain message string (for 400, 403, 404) or a list of
    `{loc, msg}` objects for 422 validation/changeset errors.
    """

    require OpenApiSpex

    OpenApiSpex.schema(%{
      title: "Error",
      type: :object,
      description:
        "FastAPI-style error envelope. " <>
          "`detail` is a message string for plain errors (400, 403, 404), " <>
          "or a list of `{loc, msg}` objects for validation errors (422).",
      properties: %{
        detail: %Schema{
          oneOf: [
            %Schema{
              type: :string,
              description: "Human-readable error message.",
              example: "Not found"
            },
            %Schema{
              type: :array,
              description: "List of field-level validation errors (422 only).",
              items: %Schema{
                type: :object,
                properties: %{
                  loc: %Schema{
                    type: :array,
                    items: %Schema{type: :string},
                    description: "Location path to the invalid field, e.g. [\"body\", \"email\"]."
                  },
                  msg: %Schema{
                    type: :string,
                    description: "Human-readable description of the validation failure."
                  }
                },
                required: [:loc, :msg]
              }
            }
          ]
        }
      },
      required: [:detail],
      example: %{detail: "Not found"}
    })
  end

